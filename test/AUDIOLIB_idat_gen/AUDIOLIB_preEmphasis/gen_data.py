def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    numSamples = currPrm["numSamples"]
    numChannels = currPrm["numChannels"]
    isInterleaved = currPrm["isInterleaved"]
    samplingRate = currPrm["samplingRate"]
    # timeConstant = currPrm["timeConstant"]
    alpha = currPrm["alpha"]

    strideIn0 = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    numExecReps = currPrm["numExecReps"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    C7100 = currPrm["C7100"]

    if testType in ["STATIC", "SINE", "SWEEP"]:
        in_data = f"staticRefInCase{testId}"
        out_data = f"staticRefOutCase{testId}"
        c_testType = "STATIC"
    else:
        in_data = "NULL"
        out_data = "NULL"
        c_testType = testType

    if C7100 == "FALSE":
        testParamsFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )


    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % ((c_testType)))
    idatFile.write("%s, // Input buffer\n" % ((in_data)))
    idatFile.write("%s, // Output buffer \n" % ((out_data)))
    idatFile.write("%s, // precision \n" % ((AUDIOLIB_utils.resolve_dType(dType))))
    idatFile.write("%s, // numSamples \n" % ((numSamples)))
    idatFile.write("%s, // numChannels \n" % ((numChannels)))
    idatFile.write("%d, // isInterleaved. \n" % (int(isInterleaved)))
    # idatFile.write("%f, // time constant. \n" % (float(timeConstant)))
    idatFile.write("%f, // alpha. \n" % (float(alpha)))


    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn0 \n"
        % ((strideIn0), (dType))
    )
    idatFile.write(
        "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
        % ((strideOut), (dType))
    )
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // numExecReps. \n" % (int(numExecReps)))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif\n")

    if C7100 == "FALSE":
        testParamsFile.write("#endif // if !defined(__C7100__)\n")

    idatFile.write("\n\n")

def reshape_audio(flat_data, currPrm, interleaved=False):
    """
    Reshape flat audio buffer into:
    data[numChannels][totalSamples]
    """    
    numFrames = currPrm["numExecReps"]
    numChannels = currPrm["numChannels"]
    numSamples = currPrm["numSamples"]
    
    flat_data = np.asarray(flat_data)
    
    if interleaved:
        data = flat_data.reshape(numFrames,numSamples,numChannels)
        return data.transpose(2, 0, 1).reshape( numChannels, numFrames * numSamples)
        
    else:
        frame_size = numChannels * numSamples
        data = flat_data.reshape(numFrames, frame_size)    
        channels = []
        for ch in range(numChannels):
            ch_data = data[ :, ch * numSamples:(ch + 1) * numSamples]
            channels.append(ch_data.reshape(-1))
        
        return np.vstack(channels)

def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "AUDIOLIB_preEmphasis_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] in ["STATIC", "SINE", "SWEEP"]:
            AUDIOLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static AUDIOLIB_preEmphasis_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)

def save_wav_file(filename, signal_data, testCase, is_interleaved=True):
    os.makedirs(os.path.dirname(filename), exist_ok=True)

    num_channels = testCase["numChannels"]
    num_samples = testCase["numSamples"]
    num_frames = testCase["numExecReps"]
    sampling_rate = testCase["samplingRate"]
        
    signal_arr = np.asarray(signal_data, dtype=np.float32)
        
    bit_depth = 32
        
    with wave.open(filename, "wb") as wf:
        
        wf.setnchannels(num_channels)
        wf.setframerate(sampling_rate)
            
        if bit_depth == 32:
            wf.setsampwidth(4)
            scale = 2147483647.0
            dtype = np.int32
        else:
            wf.setsampwidth(2)
            scale = 32767.0
            dtype = np.int16
 
        peak = np.max(np.abs(signal_arr))
        gain = 1.0
            
        if peak > 1.0:
            gain = 1.0 / peak
            signal_arr = signal_arr * gain
            
        # Clamp before the int cast: in float32, 1.0 * 2147483647.0 rounds to 2^31, one past the int32
        # maximum, which NumPy reports as an invalid cast. In-range samples are unchanged.
        int_info = np.iinfo(dtype)

        def to_int(x):
            x = np.nan_to_num(np.asarray(x, dtype=np.float64), nan=0.0)
            return np.clip(x, int_info.min, int_info.max).astype(dtype)
            
        if is_interleaved:
            audio = to_int(signal_arr * scale)
            wf.writeframes(
                np.ascontiguousarray(audio).tobytes())
                
        else:
                
            frame_size = num_channels * num_samples
                
            for f in range(num_frames):
                    
                start = f * frame_size
                end = start + frame_size
                frame = signal_arr[start:end]

                frame = frame.reshape(
                    num_channels,
                    num_samples
                ).T
                    
                frame = to_int(frame * scale)

                wf.writeframes(
                    np.ascontiguousarray(frame).tobytes()
                )
                    

def plot_audio(flat_input, flat_preemphasis,
               currPrm,
               testcase_name="testcase", output_root="plots",
               interleaved=0, num_plot_frames=6):
    numFrames, numChannels, numSamples, Fs = currPrm["numExecReps"], currPrm["numChannels"], currPrm["numSamples"], currPrm["samplingRate"]
    test_type = currPrm.get("testType", "").upper()

    # Reshape and aggregate data
    if  test_type == "SWEEP":
        max_samples = min(numFrames * numSamples, Fs)
    else:
        max_samples = min(numFrames * numSamples, 1024)

    input_data = reshape_audio(flat_input, currPrm, interleaved == 1)
    output_data = reshape_audio(flat_preemphasis, currPrm, interleaved == 1) 

    testcase_dir = os.path.join(output_root, testcase_name)
    os.makedirs(testcase_dir, exist_ok=True)

    # --------------------------------------------------
    # TIME DOMAIN PLOT
    # --------------------------------------------------
    total_samples = min(max_samples, input_data.shape[1])
    time_ms = np.arange(total_samples) / Fs * 1000.0
    
    fig, ax = plt.subplots(figsize=(16, 4))
    ax.plot(time_ms, input_data[0, :total_samples], label="Original Input")
    ax.plot(time_ms, output_data[0, :total_samples], label="Pre-emphasis")
    ax.set(title=f"Channel 0", xlabel="Time (ms)", ylabel="Amplitude")
    ax.grid(True, alpha=0.3)
    ax.legend()

    max_frames = int(np.ceil(total_samples / numSamples))
    for f in range(1, max_frames):
        b_time = f * numSamples / Fs * 1000.0
        if b_time <= time_ms[-1]: ax.axvline(b_time, linestyle="--", alpha=0.4)

    fig.suptitle(f"{testcase_name} - Time Domain ({total_samples} Samples)")
    fig.tight_layout()
    fig.savefig(os.path.join(testcase_dir, f"time_domain_{testcase_name}.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)

    # --------------------------------------------------
    # FREQUENCY DOMAIN PLOT
    # --------------------------------------------------
    fig, ax = plt.subplots(figsize=(12, 4))
    in_full, out_full = input_data[0, :], output_data[0, :]

    if test_type == "SWEEP":

        # =====================================================
        # TRANSFER FUNCTION USING CSD/WELCH
        # =====================================================

        nperseg = min(len(in_full), 32768)

        freq, Pxy = csd(
            out_full,
            in_full,
            fs=Fs, nperseg=nperseg,
            scaling="spectrum",
        )

        _, Pxx = welch(
            in_full,
            fs=Fs, nperseg=nperseg,
            scaling="spectrum",
        )

        # Transfer function
        H = Pxy / np.maximum(Pxx, 1e-20)

        gain_db = 20 * np.log10(np.maximum(np.abs(H), 1e-20))

        # Remove ridiculous spikes
        gain_db = np.clip(gain_db, -100, 100)

        # =====================================================
        # RESPONSE PLOT
        # =====================================================

        ax.plot(
            freq, gain_db,
            color="tab:red", linewidth=1.5,
            label="Transfer Function",
        )

        # =====================================================
        # FIND 0 dB CROSSING
        # =====================================================
        zero_crossing_val = ""
        zero_crossings = np.where(np.diff(np.signbit(gain_db)))[0]

        if len(zero_crossings) > 0:
            for idx in zero_crossings[:1]:
                f1 = freq[idx]
                f2 = freq[idx + 1]
                g1 = gain_db[idx]
                g2 = gain_db[idx + 1]

                if abs(g2 - g1) > 1e-12:
                    f_zero = f1 - g1 * (f2 - f1) / (g2 - g1)
                    zero_crossing_val = f"{f_zero:.2f} Hz"                    
                    ax.plot(
                        f_zero, 0, "go",
                        markersize=6,)

        else:

            idx0 = np.argmin(np.abs(gain_db))
            # Fixed syntax error: added array indexing [idx0]
            zero_crossing_val = f"{freq[idx0]:.2f} Hz closest - {gain_db[idx0]:.2f} dB"                    

        # =====================================================
        # GAIN AT USER FREQUENCIES
        # =====================================================

        row_data = [currPrm["testId"], currPrm["alpha"], currPrm["samplingRate"]]
        target_freqs = [500, 1500, 2666, 4000, 5500, 6500, 7350, 8000, 9000, 11000, 13000, 15000, 17000, 19000]
        for f_req in target_freqs:
        
            if f_req > Fs / 2:
                row_data.append("-")
                continue

            # Interpolate gain at exact requested frequency
            gain = np.interp(f_req, freq, gain_db)

            # Nearest FFT bin (for plotting only)
            idx = np.argmin(np.abs(freq - f_req))
            actual_freq = freq[idx]
            row_data.append(f"{gain:8.2f} dB")
            ax.plot(
                actual_freq, gain, "ro", markersize=4, )

            ax.annotate(
                f"{f_req:.0f} Hz\n{gain:+.2f} dB",
                xy=(actual_freq, gain), xytext=(5, 8),
                textcoords="offset points",fontsize=7,
                bbox=dict( boxstyle="round,pad=0.2", fc="white", alpha=0.8,),
                arrowprops=dict( arrowstyle="->", lw=0.6,),
            )

        row_data.append(zero_crossing_val)
        csv_file = currPrm["csvPreEmphasisResponse"]
        file_exists = os.path.exists(csv_file)
        with open(csv_file, "a", newline="") as f:
            writer = csv.writer(f)
           
            if not file_exists:
                freq_headers = ["Test ID", "Alpha" , "samplingFrequncy"] + [f"{freq} Hz" for freq in target_freqs] + ["0db crossing Hz"]        
                writer.writerow(freq_headers)
            writer.writerow(row_data)

        # =====================================================
        # AXIS SETTINGS
        # =====================================================

        ax.set_xscale("log")
        ax.set(
            title="Channel 0 - Transfer Function",
            xlabel="Frequency (Hz)",
            ylabel="Gain (dB)", xlim=(20, Fs / 2),)

        ax.grid(True, which="both", alpha=0.4)
        ax.legend()
    else:
        freq_fft = np.fft.rfftfreq(len(in_full), d=1.0 / Fs)
        in_fft, out_fft = np.abs(np.fft.rfft(in_full)), np.abs(np.fft.rfft(out_full))
        
        ax.plot(freq_fft, in_fft, label="Original Input", color="tab:blue")
        ax.plot(freq_fft, out_fft, label="Pre-emphasis", color="tab:orange")

        max_fft = np.max(in_fft) if len(in_fft) > 0 else 0
        peaks, _ = find_peaks(in_fft, height=max_fft * 0.05) if max_fft > 0 else (np.array([]), {})
        if len(peaks) > 5: peaks = peaks[np.argsort(in_fft[peaks])[-5:]]

        for p in peaks:
            f_peak, in_mag, out_mag = freq_fft[p], in_fft[p], out_fft[p]
            g_db = 20.0 * np.log10(max(out_mag, 1e-12) / max(in_mag, 1e-12))
            ax.plot(f_peak, in_mag, "bo", markersize=5)
            ax.plot(f_peak, out_mag, "ro", markersize=5)
            ax.annotate(f"{f_peak:.0f} Hz | In:{in_mag:.1f} | Out:{out_mag:.1f} | {g_db:+.2f} dB", 
                        xy=(f_peak, max(in_mag, out_mag)), xytext=(8, 8), textcoords="offset points", fontsize=7,
                        bbox=dict(boxstyle="round,pad=0.25", fc="white", alpha=0.85), arrowprops=dict(arrowstyle="->", lw=0.8))

        ax.set(title="Channel 0 - FFT Magnitude", xlabel="Frequency (Hz)", ylabel="Magnitude", xlim=(0, Fs / 2))

    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.suptitle(f"{testcase_name} - Frequency Domain")
    fig.tight_layout()
    fig.savefig(os.path.join(testcase_dir, f"frequency_domain_{testcase_name}.png"), dpi=150, bbox_inches="tight")
    plt.close(fig)

def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    testCase["testId"] = int(testCase["ID"])
    testCase["numChannels"] = int(testCase["numChannels"])
    testCase["numSamples"] = int(testCase["numSamples"])
    testCase["strideIn0"] = int(testCase["strideInElements"])
    testCase["strideOut"] = int(testCase["strideOutElements"])
    testCase["isInterleaved"] = int(testCase["isInterleaved"])
    testCase["alpha"] = float(testCase["alpha"])
    testCase["numExecReps"] = int(testCase["numExecReps"])
    testCase["samplingRate"] =  int(testCase["samplingRate"])
    testCase["testType"] = testCase["testType"].strip().upper()
    testCase["C7100"] = testCase["C7100"].strip().upper()
    testCase["frequencyLow"] = int(testCase["frequencyLow"])
    testCase["frequencyHigh"] = int(testCase["frequencyHigh"])
    testCase["writeWav"] = testCase["writeWav"].strip().upper()
    testCase["plotGraph"] = testCase["plotGraph"].strip().upper()
    testCase["csvPreEmphasisResponse"] = "preEmphasis_response.csv"

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    dType = testCase["dType"]
    numChannels = testCase["numChannels"]
    numSamples = testCase["numSamples"]
    isInterleaved = testCase["isInterleaved"]
    numExecReps = testCase["numExecReps"]
    alpha = testCase["alpha"]

    samplingRate = testCase["samplingRate"]
    testType = testCase["testType"]
    target_lowFreq = testCase["frequencyLow"]
    target_highFreq = testCase["frequencyHigh"]
    isInterleaved = testCase["isInterleaved"]
    

    [minVal, maxVal] = [-10, 10]

    if isInterleaved:
        pInLocal = np.zeros((numExecReps, numSamples, numChannels), dtype=np.float32)
    else:
        pInLocal = np.zeros((numExecReps, numChannels, numSamples), dtype=np.float32)

     # Create an instance of AUDIOLIB_preEmphasis
    preEmphasis_processor = AUDIOLIB_preEmphasis(
                dType=dType, numChannels=numChannels, 
                numSamples=numSamples, isInterleaved = isInterleaved,
                numExecReps = numExecReps, alpha = alpha)

    lowGain = 0.5
    highGain = 0.5

    max_peak = lowGain + highGain
    scale = 0.95 / max_peak

    lowGain *= scale
    highGain *= scale    

    N = numExecReps * numSamples if numExecReps < 4 else 1024   
    bin_res = samplingRate / float(N)

    if testType.strip().upper() == "SINE":
        target_lowFreq = round(target_lowFreq / bin_res) * bin_res
        target_highFreq = round(target_highFreq / bin_res) * bin_res


    for frame in range(numExecReps):
        sample_idx = np.arange(numSamples) + frame * numSamples
        t = sample_idx / float(samplingRate)

        for ch in range(numChannels):
            if testType.strip().upper() == "SINE":
                mono_signal = ((highGain * np.sin(2.0 * np.pi * target_lowFreq * t) + 
               (lowGain * np.sin( 2.0 * np.pi * target_highFreq * t)))).astype(np.float32)
               
            elif testType.strip().upper() == "SWEEP":
                        total_duration = (numSamples * numExecReps) / float(samplingRate)
                        f_start = 20.0
                        f_end =  20000.0
            
                        phase = 2.0 * np.pi * (
                            f_start * t +
                            ((f_end - f_start) / (2.0 * total_duration)) * (t ** 2)
                        )
                        mono_signal = (0.8 * np.sin(phase)).astype(np.float32)
            elif testType.strip().upper() == "STATIC":
                mono_signal = np.random.uniform(
                    low=minVal,
                    high=maxVal,
                    size=numSamples
                ).astype(np.float32)

            if isInterleaved:
                # Interleaved shape per frame: (numSamples, numChannels)
                pInLocal[frame, :, ch] = mono_signal
            else:
                # Non-interleaved shape per frame: (numChannels, numSamples)
                pInLocal[frame, ch, :] = mono_signal

    out = preEmphasis_processor.exec(pInLocal)

    in_list = np.array(pInLocal).flatten().tolist() #pInLocal.flatten().tolist()
    preemphasis_list = np.array(out).flatten().tolist()

    if testCase["writeWav"] == "TRUE":
            wav_dir = os.path.join("wav_outputs", f"case_{testId}")
            save_wav_file(os.path.join(wav_dir, f"input_case_{testId}.wav"), in_list, testCase, is_interleaved=(isInterleaved == 1))
            save_wav_file(os.path.join(wav_dir, f"output_case_{testId}.wav"), preemphasis_list, testCase, is_interleaved=(isInterleaved == 1))

    if testCase["plotGraph"] == "TRUE":
        # plot_dir = os.path.join("plot_signal", f"case_{testId}")
        plot_audio(in_list, preemphasis_list,
               testCase,
                   testcase_name=f"input_case_{testId}", output_root="plots",
               interleaved=testCase["isInterleaved"], num_plot_frames=6)
                
    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in_list, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


