def write_attributes(f, attributes, stringToWrite):
    f.write("#ifdef WIN32\n")
    f.write(stringToWrite)
    f.write("#else\n")
    f.write(attributes + stringToWrite)
    f.write("#endif\n")
    f.write("{\n")


def write_header_file(
    individual_inputs, merged_output, testCase, headerFileName, inChannelsArray=None
):
    """
    Generates a C header file containing multiple individual input arrays and the final
    aggregated output array.
    All logic for writing C arrays is contained within this function.

    Args:
        individual_inputs (list of np.array): List of generated input arrays.
        merged_output (np.array): The final aggregated buffer.
        testCase (dict): Dictionary with test case parameters.
        headerFileName (str): The name of the output header file.
        inChannelsArray (str, optional): Deprecated parameter, no longer used.
    """
    testId = testCase["ID"]
    dType = testCase["dType"]
    isInterleave = testCase["isInterleave"]

    outputDir = "../../AUDIOLIB_concat/test_data/"
    if not os.path.exists(outputDir):
        os.makedirs(outputDir)

    filepath = os.path.join(outputDir, headerFileName)

    with open(filepath, "w") as f:
        f.write(f"/* Autogenerated test data for Test Case ID: {testId} */\n")
        f.write(
            "/* This file contains all individual inputs, the expected merged output, and channel counts. */\n\n"
        )

        # --- Block to write individual input arrays ---
        f.write(
            "/* ====================================================================== */\n"
        )
        f.write(
            f"/* Individual Source Inputs (isInterleave = {isInterleave})             */\n"
        )
        f.write(
            "/* ====================================================================== */\n\n"
        )
        for i, input_array in enumerate(individual_inputs):
            array_size = input_array.size
            array_name = f"staticRefInput{i}Case{testId}"

            # Construct the full declaration strings for each platform
            win_declaration = f"static {dType} {array_name}[{array_size}] =\n"
            nix_declaration = f'__attribute__((section(".staticData"))) static {dType} {array_name}[{array_size}] =\n'

            f.write("#ifdef WIN32\n")
            f.write(win_declaration)
            f.write("#else\n")
            f.write(nix_declaration)
            f.write("#endif\n")
            f.write("{\n")

            # Individual inputs are always planar (deinterleaved)
            if input_array.ndim == 1:
                input_array = np.atleast_2d(input_array)

            rows, cols = input_array.shape
            for r in range(rows):
                f.write("    ")
                for c in range(cols):
                    val = input_array[r, c]
                    if "float" in dType or "double" in dType:
                        f.write(f"{val:.8f}f, ")
                    else:
                        f.write(f"{val}, ")
                f.write("\n")

            f.write("};\n\n")

        # --- Block to write the final merged output array ---
        f.write(
            "/* ====================================================================== */\n"
        )
        f.write(f"/* Final Merged Output (isInterleave = {isInterleave})          */\n")
        f.write(
            "/* ====================================================================== */\n\n"
        )
        array_size = merged_output.size
        merged_array_name = f"staticRefOutCase{testId}"

        win_declaration = f"static {dType} {merged_array_name}[{array_size}] =\n"
        nix_declaration = f'__attribute__((section(".staticData"))) static {dType} {merged_array_name}[{array_size}] =\n'

        f.write("#ifdef WIN32\n")
        f.write(win_declaration)
        f.write("#else\n")
        f.write(nix_declaration)
        f.write("#endif\n")
        f.write("{\n")

        if merged_output.ndim == 1:
            merged_output = np.atleast_2d(merged_output)

        rows, cols = merged_output.shape
        for r in range(rows):
            f.write("    ")
            for c in range(cols):
                val = merged_output[r, c]
                if "float" in dType or "double" in dType:
                    f.write(f"{val:.8f}f, ")
                else:
                    f.write(f"{val}, ")
            f.write("\n")
        f.write("\n};")
        f.write("\n\n")
        f.close()

    if platform == "linux" or platform == "linux2":
        call(
            [
                "indent",
                "-nut",
                "-i3",
                # "-c55",
                "-l100",
                outputDir + headerFileName,
            ]
        )
        call(["rm", outputDir + headerFileName + "~"])  # remove backup file
