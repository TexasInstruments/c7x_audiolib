def gen_testCaseParams(testParamsFile, currPrm):
    """Generate and write test case parameters to idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    inChannels = currPrm["inChannels"]
    inSamples = currPrm["inSamples"]
    isInterleave = currPrm["isInterleave"]
    downSampleRatio = currPrm["downSampleRatio"]
    phase = currPrm["phase"]
    strideIn0 = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    alignStride = currPrm["alignStride"]
    C7100 = currPrm["C7100"]

    if testType == "STATIC":
        in0 = "staticRefIn0Case" + testId
        out = "staticRefOutCase" + testId
    else:
        in0 = "NULL"
        out = "NULL"

    if C7100 == "FALSE":
        testParamsFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        testParamsFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    testParamsFile.write("{\n")
    testParamsFile.write("%s, // Test pattern \n" % ((testType)))
    testParamsFile.write("%s, // Input buffer\n" % ((in0)))
    testParamsFile.write("%s, // Output buffer \n" % ((out)))
    testParamsFile.write("%s, // inSamples \n" % ((inSamples)))
    testParamsFile.write("%s, // inChannels \n" % ((inChannels)))
    testParamsFile.write("%s, // isInterleave \n" % ((isInterleave)))
    testParamsFile.write("%s, // downSampleRatio \n" % ((downSampleRatio)))

    if alignStride =="FALSE":
        # testParamsFile.write("%s, // strideIn0 \n" % ((strideIn0)))
        testParamsFile.write("%s * sizeof(%s), // strideIn0 \n" % ((strideIn0,dType)))
        testParamsFile.write("%s * sizeof(%s), // strideOut \n" % ((strideOut,dType)))
    else:
        testParamsFile.write("AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn0 \n" % ((strideIn0), (dType)))
        testParamsFile.write("AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n" % ((strideOut), (dType)))    
        
    testParamsFile.write("%s, // precision \n" % ((AUDIOLIB_utils.resolve_dType(dType))))
    testParamsFile.write("%s, // Output data location \n" % (outputDataLocation))
    testParamsFile.write("%d, // number of reps. \n" % (int(numReps)))
    testParamsFile.write("%d, // test ID\n" % int(testId))
    testParamsFile.write("%d, // phase\n" % int(phase))
    testParamsFile.write("},\n")
    testParamsFile.write("#endif\n")

    if C7100 == "FALSE":
        testParamsFile.write("#endif // if !defined(__C7100__)\n")

    testParamsFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the idat file

    Args:
        param1 (file object): Input file object to idat.c file
        param2 (dict object): Dict object with test case parameter

    """

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "AUDIOLIB_downSample_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # generate ifdefs for header files
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            AUDIOLIB_utils.gen_ifdefs(idatFile, testCase)

    # generate parameters for test cases
    idatFile.write("static AUDIOLIB_downSample_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()

    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert str to int for necessary parameters

    Args:
        Param1(:obj: dict) : Dictionary object with test case parameters

    Returns:
        Obj: Dictionary object with necessary parameters converted to int

    """

    # print(testCase.keys())
    testCase["testId"] = int(testCase["ID"])
    testCase["inChannels"] = int(testCase["inChannels"])
    testCase["inSamples"] = int(testCase["inSamples"])
    testCase["isInterleave"] = int(testCase["isInterleave"])
    testCase["strideIn0"] = int(testCase["strideInElements"])
    testCase["strideOut"] = int(testCase["strideOutElements"])
    testCase["downSampleRatio"] = int(testCase["downSampleRatio"])
    testCase["phase"] = int(testCase["phase"])
    if testCase['downSampleRatio'] <= 0:
        raise ValueError(
                    f"downSampleRatio must be greater than 0, got {testCase['downSampleRatio']} "
                    f"for test ID {testCase['testId']}")
    if not (0 <= testCase['phase'] < testCase['downSampleRatio']):
        raise ValueError(
                    f"phase must satisfy 0 <= phase < downSampleRatio, got phase={testCase['phase']} "
                    f"downSampleRatio={testCase['downSampleRatio']} for test ID {testCase['testId']}")

    return testCase


def gen_test_case_header_file(testCase):
    """Generate test case and write out input, filter, and output tensor
    into a header file usable in C/C++ code.

    Args:
        param1 (:obj: dict): A dict object with all the test case
        parameters

    Returns:
        [int int]: Minimum and maximum value in output feature tensor

    """

    ##############################
    # Get test parameter of case #
    ##############################

    testId = testCase["ID"]
    dType = testCase["dType"]
    inChannels = testCase["inChannels"]
    inSamples = testCase["inSamples"]
    isInterleave = testCase["isInterleave"]
    downSampleRatio = testCase["downSampleRatio"]
    phase = testCase["phase"]

    # Create an instance of AUDIOLIB_downSample
    downSample_processor = AUDIOLIB_downSample(
        dType=dType,
        inChannels=inChannels,
        inSamples=inSamples,
        isInterleave=isInterleave,
        downSampleRatio=downSampleRatio,
        phase=phase
    )

    # [minVal, maxVal] = AUDIOLIB_utils.minMaxVal(dType)
    [minVal, maxVal] = [-10, 10]

    if dType[0] == "f":
        in0 = np.random.uniform(low=minVal, high=maxVal, size=(inChannels,inSamples)).astype("float32")
        
    elif dType[0] == "d":
        in0 = np.random.uniform(low=minVal, high=maxVal, size=(inChannels,inSamples)).astype("double")
    
    # Store original input for header file generation
    in0_original = in0.copy()
    
    # Apply interleaving if needed before processing
    if isInterleave:
        in0 = in0.T
    
    # Execute the downSample algorithm using the class
    out = downSample_processor.exec(in0)
    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


