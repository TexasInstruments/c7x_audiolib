def gen_test_case(testCase):
    if testCase["testType"] == "STATIC":
        inChannelsList = ast.literal_eval(testCase["inChannels"])
        inChannelsArray = ", ".join(str(ch) for ch in inChannelsList)
        [minY, maxY] = gen_test_case_header_file(testCase, inChannelsArray)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as tesType is RANDOM",
        )


