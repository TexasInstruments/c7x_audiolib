def gen_testCaseParams(idatFile, currPrm):
    """Generate and write one test-case parameter entry to the idat file.

    Args:
        idatFile (file object): open handle to the AUDIOLIB_upSample_idat.c file
        currPrm (dict): one test-case parameter row
    """

    testId = currPrm["ID"]
    dType = currPrm["dType"]
    inChannels = currPrm["inChannels"]
    inSamples = currPrm["inSamples"]
    upFactor = currPrm["upFactor"]
    phase = currPrm["phase"]
    isInterleave = currPrm["isInterleave"]
    strideIn = currPrm["strideInElements"]
    strideOut = currPrm["strideOutElements"]
    testType = currPrm["testType"]
    demoCase = currPrm["demoCase"]
    outputDataLocation = currPrm["outputDataLocation"]
    numReps = currPrm["numReps"]
    alignStride = currPrm["alignStride"]
    C7100 = currPrm["C7100"]

    if testType == "STATIC":
        inBuf = "staticRefInCase" + testId
        outBuf = "staticRefOutCase" + testId
    else:
        inBuf = "NULL"
        outBuf = "NULL"

    if C7100 == "FALSE":
        idatFile.write("#if !defined(__C7100__)\n")

    if demoCase == "true":
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d) || defined(DEMO_CASE))\n"
            % (int(testId))
        )
    else:
        idatFile.write(
            "#if (defined(ALL_TEST_CASES) || (TEST_CASE == %d))\n" % (int(testId))
        )

    # NOTE: field order here is the AUDIOLIB_upSample_testParams_t contract;
    #       the C-side struct (src/AUDIOLIB_upSample/..._priv.h) must match it.
    idatFile.write("{\n")
    idatFile.write("%s, // Test pattern \n" % (testType))
    idatFile.write("%s, // Input buffer\n" % (inBuf))
    idatFile.write("%s, // Output buffer \n" % (outBuf))
    idatFile.write("%s, // inSamples \n" % (inSamples))
    idatFile.write("%s, // inChannels \n" % (inChannels))
    idatFile.write("%s, // upFactor \n" % (upFactor))
    idatFile.write("%s, // phase \n" % (phase))
    idatFile.write("%s, // isInterleave \n" % (isInterleave))
    if alignStride == "FALSE":
        # tight (contiguous) byte stride -- the natural layout for interleaved data
        idatFile.write("%s * sizeof(%s), // strideIn \n" % ((strideIn), (dType)))
        idatFile.write("%s * sizeof(%s), // strideOut \n" % ((strideOut), (dType)))
    else:
        # 64-byte aligned row stride
        idatFile.write(
            "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideIn \n"
            % ((strideIn), (dType))
        )
        idatFile.write(
            "AUDIOLIB_CALC_STRIDE(%s * sizeof(%s), AUDIOLIB_ALIGN_SHIFT_64BYTES), // strideOut \n"
            % ((strideOut), (dType))
        )
    idatFile.write("%s, // precision \n" % (AUDIOLIB_utils.resolve_dType(dType)))
    idatFile.write("%s, // Output data location \n" % (outputDataLocation))
    idatFile.write("%d, // number of reps. \n" % (int(numReps)))
    idatFile.write("%d, // test ID\n" % int(testId))
    idatFile.write("},\n")
    idatFile.write("#endif\n")

    if C7100 == "FALSE":
        idatFile.write("#endif // if !defined(__C7100__)\n")

    idatFile.write("\n\n")


def gen_idat_file(idatFile, testCases):
    """Generate the AUDIOLIB_upSample_idat.c file."""

    fIn = open("../common/ti_lice_header_idat.txt", "r")
    lines = fIn.readlines()
    fIn.close()
    idatFile.writelines(lines)
    includeString = '#include "AUDIOLIB_upSample_idat.h"'
    idatFile.writelines(includeString)
    idatFile.write("\n")
    idatFile.write("/*This file is autogenerated*/\n")
    idatFile.write("/*Please do not edit*/\n")
    idatFile.write("\n\n")
    # include the per-case static reference data headers
    for testCase in testCases:
        if testCase["testType"] == "STATIC":
            AUDIOLIB_utils.gen_ifdefs(idatFile, testCase)

    # emit the parameter table
    idatFile.write("static AUDIOLIB_upSample_testParams_t testParams[] =  ")
    idatFile.write("{\n")

    for testCase in testCases:
        gen_testCaseParams(idatFile, testCase)

    idatFile.write("};\n\n")
    fIn = open("test_param_function.txt", "r")
    lines = fIn.readlines()
    idatFile.writelines(lines)


def process_test_case(testCase):
    """Convert the relevant CSV string fields to int and derive outSamples."""

    testCase["testId"] = int(testCase["ID"])
    testCase["inChannels"] = int(testCase["inChannels"])
    testCase["inSamples"] = int(testCase["inSamples"])
    testCase["upFactor"] = int(testCase["upFactor"])
    testCase["phase"] = int(testCase["phase"])
    testCase["isInterleave"] = int(testCase["isInterleave"])
    testCase["strideIn"] = int(testCase["strideInElements"])
    testCase["strideOut"] = int(testCase["strideOutElements"])
    testCase["outSamples"] = testCase["upFactor"] * testCase["inSamples"]

    return testCase


def gen_test_case_header_file(testCase):
    """Run the reference model for one case and write its data header.

    Returns:
        [min, max] of the output (for a progress print).
    """

    testId = testCase["ID"]
    dType = testCase["dType"]
    inChannels = testCase["inChannels"]
    inSamples = testCase["inSamples"]
    upFactor = testCase["upFactor"]
    phase = testCase["phase"]
    isInterleave = testCase["isInterleave"]

    # Create an instance of the reference model
    upSample_processor = AUDIOLIB_upSample(
        dType=dType,
        inChannels=inChannels,
        inSamples=inSamples,
        upFactor=upFactor,
        phase=phase,
        isInterleave=isInterleave,
    )

    [minVal, maxVal] = [-10, 10]

    # float32 ('f') and float64/double ('d') are supported; the int/uint
    # branches are kept so the matrix can be widened later via CSV rows.
    # Generate planar (inChannels, inSamples), then transpose for interleaved.
    if dType[0] == "f":
        in0 = np.random.uniform(low=minVal, high=maxVal, size=(inChannels, inSamples)).astype("float32")
    elif dType[0] == "d":
        in0 = np.random.uniform(low=minVal, high=maxVal, size=(inChannels, inSamples)).astype("double")
    elif dType[0] == "i" or dType[0] == "u":
        in0 = np.random.randint(low=minVal, high=maxVal, size=(inChannels, inSamples)).astype("int")
    else:
        raise ValueError("Unsupported dType: %s" % dType)

    if isInterleave:
        in0 = in0.T  # (inSamples, inChannels) -- interleaved memory layout

    out = upSample_processor.exec(in0)

    testCase["outSamples"] = upFactor * inSamples
    headerFileName = "staticRefCase" + str(testId) + ".h"
    file_io.write_header_file(in0, out, testCase, headerFileName)

    return [np.min(out), np.max(out)]


# CSV file with parameters for all test cases
testCasesCsvFile = "../AUDIOLIB_upSample/test_cases_list.csv"
testIdList = []  # list of test IDs that we want to generate test data
testIdList += range(0, 150)

myArgs = AUDIOLIB_utils.getCmdLineArgs()


def gen_test_case(testCase):
    if testCase["testType"] == "STATIC":
        [minY, maxY] = gen_test_case_header_file(testCase)
        print(
            "Test case generation completed for test ID",
            testCase["ID"],
            "w/ min:",
            minY,
            "and max",
            maxY,
        )
    else:
        print(
            "Skipping test case generation for test ID",
            testCase["ID"],
            "as testType is RANDOM",
        )


#############################################################################
# Open CSV file with test cases and generate header file with test data for #
# test cases of interest; based on testIdList                               #
#############################################################################

with open(testCasesCsvFile, encoding="utf-8-sig") as csv_file:
    testCaseReader = csv.DictReader(csv_file)
    testCases = list(testCaseReader)

    for testCase in testCases:
        testCase = process_test_case(testCase)

    for testCase in testCases:
        if myArgs.allCases == True:
            gen_test_case(testCase)
        elif int(testCase["ID"]) in testIdList:
            gen_test_case(testCase)


idatFileName = "../../AUDIOLIB_upSample/AUDIOLIB_upSample_idat.c"


##########################################################################
# Generate idat.c file by parsing all the test cases in the CSV file     #
##########################################################################


with open(idatFileName, "w") as idatFile:
    gen_idat_file(idatFile, testCases)


if platform == "linux" or platform == "linux2":
    call(["clang-format", "-style=file", "-i", idatFileName])
    call(["indent", "-nut", "-i3", "-c55", "-l200", idatFileName])
    call(["rm", idatFileName + "~"])  # remove backup file


print("Idat file generation completed")
